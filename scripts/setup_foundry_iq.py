"""Create or update the Foundry IQ knowledge sources and knowledge bases.

Normal search:
    content-blob-ks (kind azureBlob, pull-type ingestion from the ``content`` container)
    personal-kb     (knowledge base over content-blob-ks)

Topic graph (optional, preview, enabled with ``--topic-graph``):
    content-topic-ks  (kind searchIndex over the index generated by content-blob-ks)
    personal-topic-kb (knowledge base over content-topic-ks)
    The topic index itself is built and bound to the content index with the
    foundry-iq-skills ``topic-graph-build`` CLI (see docs/topic-graph.md).

Values are read from environment variables (populated from the azd environment by
scripts/postprovision.ps1) and the resolved names are written back with ``azd env set``.

Usage:
    uv run scripts/setup_foundry_iq.py
    uv run scripts/setup_foundry_iq.py --topic-graph
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import shutil
import subprocess
import sys
import time
from typing import Any

import httpx
from azure.identity import AzureCliCredential, ChainedTokenCredential, DefaultAzureCredential

EXIT_SUCCESS = 0
EXIT_FAILURE = 1
EXIT_ERROR = 2

GA_API_VERSION = "2026-10-01"
PREVIEW_API_VERSION = "2026-11-01-preview"
SEARCH_SCOPE = "https://search.azure.com/.default"
ARM_SCOPE = "https://management.azure.com/.default"
RETRY_SECONDS = 30
RETRY_ATTEMPTS = 20

RETRIEVAL_INSTRUCTIONS = (
    "Personal knowledge base of collected news, blog posts, release notes and papers. "
    "Prefer recent documents when the question is about trends or latest updates. "
    "Queries may be in Japanese or English; search both languages when useful."
)

logger = logging.getLogger(__name__)


class SetupError(Exception):
    """Raised when the setup cannot continue."""


def require_env(name: str) -> str:
    """Return a required environment variable or raise SetupError."""
    value = os.environ.get(name, "").strip()
    if not value:
        raise SetupError(f"Environment variable {name} is required (run from the azd hook or export it).")
    return value


def credential() -> ChainedTokenCredential:
    """Prefer the Azure CLI login used by azd hooks, then fall back to DefaultAzureCredential."""
    return ChainedTokenCredential(AzureCliCredential(), DefaultAzureCredential(exclude_cli_credential=True))


class Http:
    """Small authenticated JSON client with retry for RBAC propagation delays."""

    def __init__(self, scope: str) -> None:
        self._cred = credential()
        self._scope = scope
        self._client = httpx.Client(timeout=120)

    def _headers(self) -> dict[str, str]:
        token = self._cred.get_token(self._scope).token
        return {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}

    def request(self, method: str, url: str, body: dict[str, Any] | None = None, *, retry: bool = True) -> httpx.Response:
        """Send a request, retrying on 401/403/429/5xx while role assignments propagate."""
        attempts = RETRY_ATTEMPTS if retry else 1
        for attempt in range(1, attempts + 1):
            resp = self._client.request(method, url, headers=self._headers(), json=body)
            if resp.status_code < 400 or resp.status_code == 404:
                return resp
            if resp.status_code in (401, 403, 429) or resp.status_code >= 500:
                if attempt < attempts:
                    logger.warning("%s %s -> %s, retrying in %ss (%s/%s)", method, url.split("?")[0], resp.status_code, RETRY_SECONDS, attempt, attempts)
                    time.sleep(RETRY_SECONDS)
                    continue
            raise SetupError(f"{method} {url} failed: {resp.status_code} {resp.text}")
        raise SetupError(f"{method} {url} failed after retries")


def resolve_openai_endpoint(arm: Http, subscription: str, resource_group: str, account: str) -> str:
    """Return the Azure OpenAI endpoint (https://<sub-domain>.openai.azure.com/) of the Foundry account."""
    url = (
        f"https://management.azure.com/subscriptions/{subscription}/resourceGroups/{resource_group}"
        f"/providers/Microsoft.CognitiveServices/accounts/{account}?api-version=2025-06-01"
    )
    resp = arm.request("GET", url)
    if resp.status_code == 404:
        raise SetupError(f"Foundry account {account} not found in {resource_group}.")
    props = resp.json().get("properties", {})
    endpoints = props.get("endpoints", {})
    endpoint = endpoints.get("OpenAI Language Model Instance API") or f"https://{props.get('customSubDomainName', account)}.openai.azure.com/"
    return endpoint if endpoint.endswith("/") else endpoint + "/"


def aoai_model(resource_uri: str, deployment: str, model: str) -> dict[str, Any]:
    """Build an azureOpenAI model reference payload."""
    return {
        "kind": "azureOpenAI",
        "azureOpenAIParameters": {"resourceUri": resource_uri, "deploymentId": deployment, "modelName": model},
    }


def build_blob_knowledge_source(name: str, storage_id: str, container: str, aoai: str, embedding: str) -> dict[str, Any]:
    """Payload for the azureBlob knowledge source (auto-creates data source, skillset, index, indexer)."""
    return {
        "name": name,
        "kind": "azureBlob",
        "description": "Normalized documents collected daily by the collector function (Markdown with front matter).",
        "azureBlobParameters": {
            "connectionString": f"ResourceId={storage_id};",
            "containerName": container,
            "folderPath": None,
            "isADLSGen2": False,
            "ingestionParameters": {
                # Documents are Markdown, so image verbalization (and its chat model) is not needed.
                "disableImageVerbalization": True,
                "embeddingModel": aoai_model(aoai, embedding, embedding),
                "contentExtractionMode": "minimal",
                "ingestionSchedule": None,
            },
        },
    }


def build_knowledge_base(name: str, sources: list[str], aoai: str, chat: str, description: str) -> dict[str, Any]:
    """Payload for a knowledge base that returns extracted evidence to the agent."""
    return {
        "name": name,
        "description": description,
        "knowledgeSources": [{"name": s} for s in sources],
        "models": [aoai_model(aoai, chat, chat)],
        "retrievalReasoningEffort": {"kind": "low"},
        "outputMode": "extractiveData",
        "retrievalInstructions": RETRIEVAL_INSTRUCTIONS,
    }


def find_index_fields(index: dict[str, Any]) -> tuple[str, list[str]]:
    """Return (vector field, returned text/source fields) from an index definition."""
    fields = index.get("fields", [])
    vector = next((f["name"] for f in fields if f.get("type") == "Collection(Edm.Single)"), None)
    text_candidates = [f["name"] for f in fields if f.get("type") == "Edm.String" and f.get("searchable")]
    text = next((n for n in ("content", "chunk", "snippet", "text") if n in text_candidates), text_candidates[0] if text_candidates else None)
    if not vector or not text:
        raise SetupError(f"Could not detect vector/text fields in index {index.get('name')}.")
    names = {f["name"] for f in fields if f.get("retrievable", True)}
    # blob_url / snippet_parent_id let the agent cite and open the original document.
    return vector, [text, *(n for n in ("blob_url", "snippet_parent_id") if n in names)]


def build_topic_knowledge_source(name: str, index_name: str, vector_field: str, data_fields: list[str]) -> dict[str, Any]:
    """Payload for the searchIndex knowledge source used for topic graph retrieval (preview).

    No topic graph default is stored here: the topic index binding is applied by the
    foundry-iq-skills `configure-retrieval` step and the agent sets `topicGraph` per request.
    """
    return {
        "name": name,
        "kind": "searchIndex",
        "description": "Topic-graph view over the collected content index (preview).",
        "searchIndexParameters": {
            "searchIndexName": index_name,
            "searchFields": [{"name": vector_field}],
            "sourceDataFields": [{"name": f} for f in data_fields],
        },
    }


def azd_env_set(values: dict[str, str]) -> None:
    """Persist values into the active azd environment when azd is available."""
    azd = shutil.which("azd")
    if not azd:
        logger.info("azd not found; skip writing %s", ", ".join(values))
        return
    for key, value in values.items():
        subprocess.run([azd, "env", "set", key, value], check=True, capture_output=True, text=True)


def create_parser() -> argparse.ArgumentParser:
    """Create and configure argument parser."""
    parser = argparse.ArgumentParser(description="Configure Foundry IQ knowledge sources and knowledge bases.")
    parser.add_argument(
        "--topic-graph",
        action="store_true",
        help="Also create the searchIndex knowledge source/base used for topic graph retrieval (preview).",
    )
    parser.add_argument("--chat-model", default=os.environ.get("KNOWLEDGE_MODEL_DEPLOYMENT_NAME", "gpt-5.4-mini"))
    parser.add_argument("--embedding-model", default=os.environ.get("EMBEDDING_MODEL_DEPLOYMENT_NAME", "text-embedding-3-large"))
    parser.add_argument("-v", "--verbose", action="store_true")
    return parser


def configure_logging(verbose: bool = False) -> None:
    """Configure logging based on verbosity level."""
    logging.basicConfig(level=logging.DEBUG if verbose else logging.INFO, format="%(levelname)s: %(message)s")
    for noisy in ("azure", "httpx"):
        logging.getLogger(noisy).setLevel(logging.WARNING)


def run(args: argparse.Namespace) -> int:
    """Create or update all Foundry IQ objects."""
    subscription = require_env("AZURE_SUBSCRIPTION_ID")
    resource_group = require_env("AZURE_RESOURCE_GROUP")
    account = require_env("AZURE_AI_ACCOUNT_NAME")
    search = require_env("SEARCH_ENDPOINT").rstrip("/")
    storage_account = require_env("STORAGE_ACCOUNT_NAME")
    content_container = os.environ.get("CONTENT_CONTAINER", "content")
    ks_name = os.environ.get("KNOWLEDGE_SOURCE_NAME") or "content-blob-ks"
    kb_name = os.environ.get("KNOWLEDGE_BASE_NAME") or "personal-kb"

    arm = Http(ARM_SCOPE)
    srch = Http(SEARCH_SCOPE)
    aoai = resolve_openai_endpoint(arm, subscription, resource_group, account)
    storage_id = (
        f"/subscriptions/{subscription}/resourceGroups/{resource_group}"
        f"/providers/Microsoft.Storage/storageAccounts/{storage_account}"
    )

    logger.info("Creating knowledge source %s", ks_name)
    ks_body = build_blob_knowledge_source(ks_name, storage_id, content_container, aoai, args.embedding_model)
    srch.request("PUT", f"{search}/knowledgesources('{ks_name}')?api-version={GA_API_VERSION}", ks_body)

    ks = srch.request("GET", f"{search}/knowledgesources('{ks_name}')?api-version={GA_API_VERSION}").json()
    created = ks.get("azureBlobParameters", {}).get("createdResources") or {}
    logger.info("Generated resources: %s", json.dumps(created))
    indexer_name = created.get("indexer") or f"{ks_name}-indexer"
    index_name = created.get("index") or f"{ks_name}-index"

    logger.info("Creating knowledge base %s", kb_name)
    kb_body = build_knowledge_base(kb_name, [ks_name], aoai, args.chat_model, "Personal knowledge base (normal search).")
    srch.request("PUT", f"{search}/knowledgebases('{kb_name}')?api-version={GA_API_VERSION}", kb_body)

    env_updates = {
        "KNOWLEDGE_SOURCE_NAME": ks_name,
        "KNOWLEDGE_BASE_NAME": kb_name,
        "SEARCH_INDEXER_NAME": indexer_name,
        "SEARCH_CONTENT_INDEX_NAME": index_name,
    }

    if args.topic_graph:
        index = srch.request("GET", f"{search}/indexes('{index_name}')?api-version={PREVIEW_API_VERSION}").json()
        vector_field, data_fields = find_index_fields(index)
        topic_ks = "content-topic-ks"
        topic_kb = "personal-topic-kb"
        topic_ks_url = f"{search}/knowledgesources('{topic_ks}')?api-version={PREVIEW_API_VERSION}"
        if srch.request("GET", topic_ks_url).status_code == 404:
            logger.info("Creating topic graph knowledge source %s over %s (%s -> %s)", topic_ks, index_name, vector_field, data_fields)
            srch.request("PUT", topic_ks_url, build_topic_knowledge_source(topic_ks, index_name, vector_field, data_fields))
        else:
            # configure-retrieval owns the source's topicGraph setting; never overwrite it.
            logger.info("Knowledge source %s already exists; left unchanged", topic_ks)
        srch.request(
            "PUT",
            f"{search}/knowledgebases('{topic_kb}')?api-version={PREVIEW_API_VERSION}",
            build_knowledge_base(topic_kb, [topic_ks], aoai, args.chat_model, "Topic graph view for broad exploration."),
        )
        env_updates.update({"TOPIC_KNOWLEDGE_SOURCE_NAME": topic_ks, "TOPIC_KNOWLEDGE_BASE_NAME": topic_kb})

    azd_env_set(env_updates)
    logger.info("Foundry IQ configured: %s", json.dumps(env_updates))
    return EXIT_SUCCESS


def main() -> int:
    """Main entry point with error handling."""
    args = create_parser().parse_args()
    configure_logging(args.verbose)
    try:
        return run(args)
    except SetupError as e:
        logger.error("%s", e)
        return EXIT_ERROR
    except KeyboardInterrupt:
        return 130
    except Exception as e:  # noqa: BLE001
        logger.exception("Unexpected error: %s", e)
        return EXIT_FAILURE


if __name__ == "__main__":
    sys.exit(main())
